"""Small project entrypoint; shared implementation is pinned to one product release."""
import re

from product_release import REPOSITORY, SHA, SEMVER, validate_manifest

WORKFLOW = '.github/workflows/plane-devflow.yml'


def workflow(commit, version):
    if not SHA.fullmatch(commit) or not SEMVER.fullmatch(version):
        raise ValueError('Expected a full product release commit and version.')
    return f'''# Generated by Plane DevFlow. No PR checkout or PR code execution.
name: Plane task sync
on:
  pull_request_target:
    types: [opened, edited, synchronize, reopened, ready_for_review, converted_to_draft, closed]
  workflow_dispatch:
permissions:
  contents: read
  pull-requests: read
concurrency:
  group: plane-devflow-${{{{ github.event.pull_request.number || 'connection-check' }}}}
  cancel-in-progress: false
jobs:
  sync:
    if: github.event_name == 'pull_request_target' || github.ref == format('refs/heads/{{0}}', github.event.repository.default_branch)
    runs-on: ubuntu-latest
    timeout-minutes: 5
    steps:
      - uses: {REPOSITORY}@{commit} # Plane DevFlow {version}
        with:
          github-token: ${{{{ github.token }}}}
          plane-api-key: ${{{{ secrets.PLANE_API_KEY }}}}
          trusted-config-sha: ${{{{ github.sha }}}}
'''


def identity(content):
    if not isinstance(content, bytes):
        return None
    try:
        text = content.decode('utf-8')
    except UnicodeError:
        return None
    match = re.search(r'      - uses: SoaringLabs/plane-devflow@([0-9a-f]{40}) # Plane DevFlow ([0-9]+\.[0-9]+\.[0-9]+)\n', text)
    if match is None:
        return None
    commit, version = match.groups()
    if text != workflow(commit, version):
        return None
    return {'commit': commit, 'version': version}


def inspect(files, config, release=None):
    from plugin_version import VERSION
    found = identity(files.get(WORKFLOW))
    if found is None:
        return None
    result = {'layout': 'shared_action', 'installed_version': found['version'], 'source_commit': found['commit'],
              'latest_known_version': VERSION, 'catalog_source': 'product_release', 'integrity_verified': None,
              'compatible': None, 'update_available': None, 'upgrade_required': None, 'status': 'unverified'}
    if release is None:
        return result
    release = validate_manifest(release)
    if found != {'version': release['version'], 'commit': release['commit']}:
        result.update(integrity_verified=False, compatible=False, status='unrecognized')
        return result
    compatible = config['version'] in release['config_versions'] and 1 in release['binding_versions']
    older = tuple(map(int, found['version'].split('.'))) < tuple(map(int, VERSION.split('.')))
    result.update(integrity_verified=True, compatible=compatible, update_available=older,
                  upgrade_required=not compatible, status='upgrade_required' if not compatible else 'update_available' if older else 'current')
    return result
