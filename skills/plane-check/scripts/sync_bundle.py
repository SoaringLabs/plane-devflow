def validate_catalog():
    """Reject ambiguous or malformed trusted metadata before making a readiness claim."""
    paths = {WORKFLOW, BUNDLE + '/action_runner.py', BUNDLE + '/plane_sync.py'}
    fingerprints = set()
    if CURRENT_VERSION not in RELEASES:
        raise ValueError('Missing current sync bundle release.')
    for version, record in RELEASES.items():
        if not isinstance(version, str) or not re.fullmatch(r'(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)', version):
            raise ValueError('Invalid sync bundle version.')
        if not isinstance(record, dict) or set(record) != {'files', 'config_versions', 'binding_versions', 'support'}:
            raise ValueError('Invalid sync bundle release metadata.')
        if not isinstance(record['files'], dict) or set(record['files']) != paths or not all(
                isinstance(value, str) and re.fullmatch(r'[0-9a-f]{64}', value) for value in record['files'].values()):
            raise ValueError('Invalid sync bundle file fingerprints.')
        fingerprint = tuple(sorted(record['files'].items()))
        if fingerprint in fingerprints:
            raise ValueError('Ambiguous sync bundle fingerprints.')
        fingerprints.add(fingerprint)
        for field in ('config_versions', 'binding_versions'):
            values = record[field]
            if not isinstance(values, list) or not values or not all(type(v) is int and v > 0 for v in values):
                raise ValueError('Invalid sync bundle compatibility metadata.')
        if record['support'] not in {'supported', 'upgrade_required'}:
            raise ValueError('Invalid sync bundle support policy.')
        if tuple(map(int, version.split('.'))) > tuple(map(int, CURRENT_VERSION.split('.'))):
            raise ValueError('Current sync bundle must be the latest known release.')
    if RELEASES[CURRENT_VERSION]['support'] != 'supported':
        raise ValueError('Current sync bundle must be supported.')


def inspect_bundle(files, config, release=None):
    """Classify exact known bytes; a project-provided version is never trusted."""
    from shared_sync import inspect
    shared = inspect(files, config, release)
    if shared is not None:
        return shared
    validate_catalog()
    result = {'installed_version': None, 'latest_known_version': CURRENT_VERSION,
              'catalog_source': 'installed_plugin', 'integrity_verified': None,
              'compatible': None, 'update_available': None, 'upgrade_required': None,
              'status': 'unverified'}
    paths = RELEASES[CURRENT_VERSION]['files']
    if any(not isinstance(files.get(path), bytes) for path in paths):
        return result
    hashes = {path: hashlib.sha256(files[path]).hexdigest() for path in paths}
    match = next(((version, entry) for version, entry in RELEASES.items() if entry['files'] == hashes), None)
    if match is None:
        result.update(integrity_verified=False, compatible=False, status='unrecognized')
        return result
    version, entry = match
    compatible = (entry['support'] == 'supported' and config['version'] in entry['config_versions']
                  and 1 in entry['binding_versions'])  # Current PR binding protocol is version 1.
    result.update(layout='legacy_vendored', legacy_bundle_version=version, installed_version=version, integrity_verified=True, compatible=compatible,
                  update_available=version != CURRENT_VERSION, upgrade_required=not compatible,
                  status='upgrade_required' if not compatible else 'update_available' if version != CURRENT_VERSION else 'current')
    return result


def verify_current_bundle():
    """Keep historical bytes intact; new runtime identity follows the product."""
    validate_catalog()
    actual = {path: hashlib.sha256(data).hexdigest() for path, data in bundled_files().items()}
    if actual != RELEASES[CURRENT_VERSION]['files']:
        raise ValueError('Current sync bundle changed without a matching release fingerprint/version update.')
