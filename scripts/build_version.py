#!/usr/bin/env python3
"""Generate distribution version fields from VERSION; --check never writes."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate(root=ROOT, *, check=False):
    root = Path(root)
    version = (root / 'VERSION').read_text().strip()
    if not re.fullmatch(r'(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)', version):
        raise ValueError('VERSION must contain a stable semantic version.')
    changes = {}
    for name in ('package.json', 'package-lock.json', 'plugins/plane-devflow/plugin.json'):
        path = root / name
        original = path.read_text()
        data = json.loads(original)
        previous = data['version']
        # Preserve formatting and unrelated package versions.
        updated = original.replace('"version": ' + json.dumps(previous), '"version": ' + json.dumps(version), 1)
        if name == 'package-lock.json':
            data = json.loads(updated)
            previous = data['packages']['']['version']
            # The root package is the first entry in npm's lockfile.
            prefix, rest = updated.split('"packages":', 1)
            updated = prefix + '"packages":' + rest.replace('"version": ' + json.dumps(previous), '"version": ' + json.dumps(version), 1)
        changes[path] = updated
    changes[root / 'plugins/plane-devflow/scripts/plugin_version.py'] = (
        '"""Generated by scripts/build_version.py from the product VERSION file."""\n'
        f'VERSION = "{version}"\n')
    drift = [str(path.relative_to(root)) for path, content in changes.items() if path.read_text() != content]
    if check and drift:
        raise ValueError('Version metadata drift: ' + ', '.join(drift))
    if not check:
        for path, content in changes.items():
            path.write_text(content)
    return {'version': version, 'changed': drift}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    print(json.dumps(generate(check=args.check)))
